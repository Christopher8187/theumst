CREATE OR REPLACE FUNCTION seed_demo_knowledge(
    p_section_key text,
    p_source_key text,
    p_demo_order int,
    p_type text,
    p_label text,
    p_statement text,
    p_working text,
    p_working_summary text
) RETURNS int
LANGUAGE plpgsql
AS $function$
DECLARE
    v_section_id int;
    v_knowledge_id int;
    v_crystal_id int;
BEGIN
    SELECT section_id INTO v_section_id FROM section WHERE source_key = p_section_key LIMIT 1;
    IF v_section_id IS NULL THEN
        RETURN NULL;
    END IF;
    SELECT knowledge_id INTO v_knowledge_id
    FROM knowledge
    WHERE section_id = v_section_id AND source_key = p_source_key;

    IF v_knowledge_id IS NULL THEN
        INSERT INTO knowledge_crystal DEFAULT VALUES RETURNING knowledge_crystal_id INTO v_crystal_id;
        INSERT INTO knowledge
            (section_id, knowledge_crystal_id, type, is_default_in_crystal, source_key, source_metadata)
        VALUES
            (v_section_id, v_crystal_id, p_type, true, p_source_key,
             jsonb_build_object('demo', true, 'demo_order', p_demo_order))
        RETURNING knowledge_id INTO v_knowledge_id;
    ELSE
        UPDATE knowledge SET
            type = p_type,
            source_metadata = jsonb_build_object('demo', true, 'demo_order', p_demo_order)
        WHERE knowledge_id = v_knowledge_id;
    END IF;

    INSERT INTO language_knowledge
        (language_id, knowledge_id, label, statement, working, working_summary)
    VALUES
        (1, v_knowledge_id, p_label, p_statement, p_working, p_working_summary)
    ON CONFLICT (language_id, knowledge_id) DO UPDATE SET
        label = EXCLUDED.label,
        statement = EXCLUDED.statement,
        working = EXCLUDED.working,
        working_summary = EXCLUDED.working_summary;

    RETURN v_knowledge_id;
END;
$function$;

