CREATE TABLE IF NOT EXISTS demo_access_request (
    user_id int PRIMARY KEY REFERENCES "user"(user_id) ON DELETE CASCADE,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'rejected')),
    request_message text NOT NULL DEFAULT '',
    review_note text NOT NULL DEFAULT '',
    requested_at timestamptz NOT NULL DEFAULT now(),
    reviewed_by_user_id int REFERENCES "user"(user_id) ON DELETE SET NULL,
    reviewed_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS user_grimoire (
    user_id int NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE,
    grimoire_id int NOT NULL REFERENCES grimoire(grimoire_id) ON DELETE CASCADE,
    summoned_at timestamptz NOT NULL DEFAULT now(),
    last_opened_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, grimoire_id)
);

CREATE TABLE IF NOT EXISTS demo_knowledge_progress (
    user_id int NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE,
    knowledge_id int NOT NULL REFERENCES knowledge(knowledge_id) ON DELETE CASCADE,
    completed boolean NOT NULL DEFAULT false,
    completed_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, knowledge_id)
);

CREATE TABLE IF NOT EXISTS demo_study_state (
    user_id int NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE,
    grimoire_id int NOT NULL REFERENCES grimoire(grimoire_id) ON DELETE CASCADE,
    current_knowledge_id int REFERENCES knowledge(knowledge_id) ON DELETE SET NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, grimoire_id)
);

CREATE TABLE IF NOT EXISTS demo_note (
    demo_note_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id int NOT NULL REFERENCES "user"(user_id) ON DELETE CASCADE,
    grimoire_id int REFERENCES grimoire(grimoire_id) ON DELETE CASCADE,
    knowledge_id int REFERENCES knowledge(knowledge_id) ON DELETE CASCADE,
    note_type text NOT NULL CHECK (note_type IN ('attached', 'scribble')),
    tag text NOT NULL DEFAULT '',
    content text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (
        (note_type = 'attached' AND knowledge_id IS NOT NULL)
        OR (note_type = 'scribble' AND knowledge_id IS NULL)
    )
);

CREATE TABLE IF NOT EXISTS demo_similarity (
    from_id int NOT NULL REFERENCES knowledge(knowledge_id) ON DELETE CASCADE,
    to_id int NOT NULL REFERENCES knowledge(knowledge_id) ON DELETE CASCADE,
    statement_score numeric(5, 4) NOT NULL CHECK (statement_score BETWEEN 0 AND 1),
    combined_score numeric(5, 4) NOT NULL CHECK (combined_score BETWEEN 0 AND 1),
    PRIMARY KEY (from_id, to_id),
    CHECK (from_id <> to_id)
);

CREATE INDEX IF NOT EXISTS demo_access_request_status_idx
