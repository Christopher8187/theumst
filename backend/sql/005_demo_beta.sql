INSERT INTO demo_similarity (from_id, to_id, statement_score, combined_score)
SELECT a.knowledge_id, b.knowledge_id, scores.statement_score, scores.combined_score
FROM (VALUES
    ('demo-vector-definition', 'demo-gradient-context', 0.8200::numeric, 0.7600::numeric),
    ('demo-linear-map-definition', 'demo-derivative-definition', 0.7900::numeric, 0.9100::numeric),
    ('demo-coordinate-notation', 'demo-gradient-context', 0.7100::numeric, 0.7300::numeric),
    ('demo-span-theorem', 'demo-derivative-definition', 0.6300::numeric, 0.6800::numeric)
) AS scores(from_key, to_key, statement_score, combined_score)
JOIN knowledge a ON a.source_key = scores.from_key
JOIN knowledge b ON b.source_key = scores.to_key
ON CONFLICT (from_id, to_id) DO UPDATE SET
    statement_score = EXCLUDED.statement_score,
    combined_score = EXCLUDED.combined_score;

